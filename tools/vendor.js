// One-off: copy third-party libraries and fonts from node_modules into vendor/ and fonts/.
// Run with: node tools/vendor.js   (only needed when upgrading a library)
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';

mkdirSync('vendor', { recursive: true });
mkdirSync('fonts', { recursive: true });

const entries = {
  'gsap.js': `export { gsap } from 'gsap';
export { SplitText } from 'gsap/SplitText';
export { DrawSVGPlugin } from 'gsap/DrawSVGPlugin';`,
  'number-flow.js': `export { default as NumberFlow } from 'number-flow';`,
  'd3.js': `export { scaleLinear, scaleBand, scaleTime } from 'd3-scale';
export { line, area, curveMonotoneX, curveLinear } from 'd3-shape';
export { extent, max, min, median, quantile } from 'd3-array';`,
  'idb.js': `export { openDB } from 'idb';`,
};

for (const [file, contents] of Object.entries(entries)) {
  await build({
    stdin: { contents, resolveDir: process.cwd(), loader: 'js' },
    bundle: true, format: 'esm', minify: true, target: ['es2020'],
    outfile: `vendor/${file}`, legalComments: 'inline', logLevel: 'warning',
  });
}
copyFileSync('node_modules/geist/dist/fonts/geist-sans/Geist-Variable.woff2', 'fonts/Geist-Variable.woff2');
copyFileSync('node_modules/geist/dist/fonts/geist-mono/GeistMono-Variable.woff2', 'fonts/GeistMono-Variable.woff2');
copyFileSync('node_modules/geist/LICENSE.txt', 'fonts/LICENSE-Geist.txt');
writeFileSync('vendor/README.md', `Bundled copies of third-party libraries (generated by tools/vendor.js).
- gsap.js: GSAP ${JSON.parse(await (await import('node:fs/promises')).readFile('node_modules/gsap/package.json','utf8')).version} + SplitText + DrawSVGPlugin (free license, gsap.com)
- number-flow.js: NumberFlow (MIT)
- d3.js: d3-scale, d3-shape, d3-array subsets (ISC)
- idb.js: idb by Jake Archibald (ISC)
`);
console.log('vendored');
